#[inline(never)]
pub fn draw_utf8(surface: &mut [u32], x: i32, y: i32, text: &[u8], color: u32) -> i32 {
    let mut index = 0;
    let mut cursor = x;
    while index < text.len() {
        let first = unsafe { *text.as_ptr().add(index) };
        if first < 0x80 {
            draw_glyph(surface, cursor, y, glyph(first), color);
            cursor += CELL_WIDTH;
            index += 1;
        } else if first == 0xe3 && index + 2 < text.len() {
            let second = unsafe { *text.as_ptr().add(index + 1) };
            let third = unsafe { *text.as_ptr().add(index + 2) };
            let glyph = match [second, third] {
                [0x81, 0x82] => Some([0x00, 0x42, 0x7e, 0x42, 0x42, 0x42, 0x7e]), // あ
                [0x83, 0xa1] => Some([0x7e, 0x08, 0x7e, 0x08, 0x7e, 0x08, 0x7e]), // メ
                _ => None,
            };
            draw_glyph(surface, cursor, y, glyph.unwrap_or(REPLACEMENT), color);
            cursor += CELL_WIDTH;
            index += 3;
        } else if first == 0xe6 && index + 2 < text.len() {
            let second = unsafe { *text.as_ptr().add(index + 1) };
            let third = unsafe { *text.as_ptr().add(index + 2) };
            let glyph = match [second, third] {
                [0x97, 0xa5] => Some([0x7e, 0x48, 0x7e, 0x48, 0x7e, 0x48, 0x7e]), // 日
                [0x9c, 0xac] => Some([0x42, 0x7e, 0x52, 0x7e, 0x52, 0x7e, 0x42]), // 本
                [0x9e, 0xa1] => Some([0x7e, 0x48, 0x7e, 0x48, 0x7e, 0x48, 0x7e]), // 語
                _ => None,
            };
            draw_glyph(surface, cursor, y, glyph.unwrap_or(REPLACEMENT), color);
            cursor += CELL_WIDTH;
            index += 3;
        } else {
            draw_glyph(surface, cursor, y, REPLACEMENT, color);
            cursor += CELL_WIDTH;
            index += 1;
        }
    }
    cursor
}

const REPLACEMENT: [u8; 7] = [0x7e, 0x42, 0x5a, 0x42, 0x5a, 0x42, 0x7e];

fn draw_glyph(surface: &mut [u32], x: i32, y: i32, rows: [u8; 7], color: u32) {
    let mut row = 0;
    while row < GLYPH_HEIGHT {
        let mut column = 0;
        while column < GLYPH_WIDTH {
            if rows[row as usize] & (1 << (4 - column)) != 0 {
                let pixel_x = x + column;
                let pixel_y = y + row;
                if pixel_x >= 0
                    && pixel_x < SURFACE_WIDTH as i32
                    && pixel_y >= 0
                    && pixel_y < SURFACE_HEIGHT as i32
                {
                    let index = pixel_y as usize * SURFACE_WIDTH as usize + pixel_x as usize;
                    unsafe {
                        core::ptr::write(surface.as_mut_ptr().add(index), color);
                    }
                }
            }
            column += 1;
        }
        row += 1;
    }
}

#[inline(never)]
fn glyph(byte: u8) -> [u8; 7] {
    let base: *const u8;
    unsafe {
        asm!(
            "lea {base}, [rip + NAGI_FONT_GLYPHS]",
            base = out(reg) base,
            options(nostack, preserves_flags, readonly),
        );
    }
    let mut index = 0;
    while index < GLYPH_COUNT {
        let entry = unsafe { base.add(index * 8) };
        if unsafe { core::ptr::read_volatile(entry) } == byte {
            let mut rows = [0_u8; 7];
            let mut row = 0;
            while row < 7 {
                rows[row] = unsafe { core::ptr::read_volatile(entry.add(row + 1)) };
                row += 1;
            }
            return rows;
        }
        index += 1;
    }
    REPLACEMENT
}
