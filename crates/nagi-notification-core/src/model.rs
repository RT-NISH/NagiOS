#[derive(Clone, Debug, Eq, PartialEq)]
pub struct LocalizedArgument {
    pub(crate) name: String,
    pub(crate) value: ArgumentValue,
    pub(crate) sensitivity: Sensitivity,
}

impl LocalizedArgument {
    pub fn new(
        name: impl Into<String>,
        value: ArgumentValue,
        sensitivity: Sensitivity,
    ) -> Result<Self, ValidationError> {
        let name = name.into();
        if !valid_argument_name(&name) {
            return Err(ValidationError::InvalidArgumentName);
        }
        if value_size(&value) > MAX_CONTENT_BYTES {
            return Err(ValidationError::ContentTooLarge);
        }
        Ok(Self {
            name,
            value,
            sensitivity,
        })
    }

    pub fn name(&self) -> &str {
        &self.name
    }

    pub fn value(&self) -> &ArgumentValue {
        &self.value
    }

    pub const fn sensitivity(&self) -> Sensitivity {
        self.sensitivity
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct LocalizedMessage {
    pub(crate) message_id: MessageId,
    pub(crate) arguments: Vec<LocalizedArgument>,
}

impl LocalizedMessage {
    pub fn new(
        message_id: MessageId,
        arguments: Vec<LocalizedArgument>,
    ) -> Result<Self, ValidationError> {
        if arguments.len() > MAX_LOCALIZED_ARGUMENTS {
            return Err(ValidationError::TooManyArguments);
        }
        let mut names = std::collections::BTreeSet::new();
        let total = arguments
            .iter()
            .try_fold(message_id.as_str().len(), |size, arg| {
                if !names.insert(arg.name.clone()) {
                    return Err(ValidationError::DuplicateArgument);
                }
                size.checked_add(arg.name.len())
                    .and_then(|size| size.checked_add(value_size(&arg.value)))
                    .ok_or(ValidationError::ContentTooLarge)
            })?;
        if total > MAX_CONTENT_BYTES {
            return Err(ValidationError::ContentTooLarge);
        }
        Ok(Self {
            message_id,
            arguments,
        })
    }

    pub fn message_id(&self) -> &MessageId {
        &self.message_id
    }

    pub fn arguments(&self) -> &[LocalizedArgument] {
        &self.arguments
    }

    pub fn encoded_size(&self) -> usize {
        self.message_id.as_str().len()
            + self
                .arguments
                .iter()
                .map(|argument| argument.name.len() + value_size(&argument.value))
                .sum::<usize>()
    }
}

/// User-facing content is either a shared localization reference or explicitly
/// classified user text. `Redacted` is safe to persist and is resolved by the
/// injected localization adapter for the selected locale.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum NotificationContent {
    Localized(LocalizedMessage),
    UserText {
        text: String,
        sensitivity: Sensitivity,
    },
    Redacted,
}

impl NotificationContent {
    pub fn user_text(
        text: impl Into<String>,
        sensitivity: Sensitivity,
    ) -> Result<Self, ValidationError> {
        let text = text.into();
        if text.trim().is_empty() {
            return Err(ValidationError::EmptyContent);
        }
        if text.len() > MAX_CONTENT_BYTES {
            return Err(ValidationError::ContentTooLarge);
        }
        Ok(Self::UserText { text, sensitivity })
    }

    pub fn localized(message: LocalizedMessage) -> Self {
        Self::Localized(message)
    }

    pub fn sensitivity(&self) -> Sensitivity {
        match self {
            Self::Localized(message) => message
                .arguments()
                .iter()
                .map(LocalizedArgument::sensitivity)
                .max()
                .unwrap_or(Sensitivity::Public),
            Self::UserText { sensitivity, .. } => *sensitivity,
            Self::Redacted => Sensitivity::Public,
        }
    }

    pub fn encoded_size(&self) -> usize {
        match self {
            Self::Localized(message) => message.encoded_size(),
            Self::UserText { text, .. } => text.len(),
            Self::Redacted => 0,
        }
    }
}

#[derive(Clone, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct GroupingKey(String);

impl GroupingKey {
    pub fn new(value: impl Into<String>) -> Result<Self, ValidationError> {
        let value = value.into();
        if value.trim().is_empty()
            || value.len() > MAX_GROUPING_KEY_BYTES
            || value.chars().any(char::is_control)
        {
            return Err(ValidationError::InvalidGroupingKey);
        }
        Ok(Self(value))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

