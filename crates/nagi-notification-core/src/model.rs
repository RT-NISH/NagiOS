/// Opaque, stable ID generated by an injected ID source.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct NotificationId([u8; MAX_NOTIFICATION_ID_BYTES]);

impl NotificationId {
    pub fn new(bytes: [u8; MAX_NOTIFICATION_ID_BYTES]) -> Result<Self, ValidationError> {
        if bytes.iter().all(|byte| *byte == 0) {
            return Err(ValidationError::InvalidNotificationId);
        }
        Ok(Self(bytes))
    }

    pub const fn as_bytes(&self) -> &[u8; MAX_NOTIFICATION_ID_BYTES] {
        &self.0
    }
}

