#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ActionParameter {
    pub(crate) name: String,
    pub(crate) value: ActionValue,
    pub(crate) sensitivity: Sensitivity,
}

impl ActionParameter {
    pub fn new(
        name: impl Into<String>,
        value: ActionValue,
        sensitivity: Sensitivity,
    ) -> Result<Self, ValidationError> {
        let name = name.into();
        if !valid_argument_name(&name) {
            return Err(ValidationError::InvalidArgumentName);
        }
        if action_value_size(&value) > MAX_CONTENT_BYTES {
            return Err(ValidationError::ContentTooLarge);
        }
        Ok(Self {
            name,
            value,
            sensitivity,
        })
    }

    pub fn name(&self) -> &str {
        &self.name
    }

    pub fn value(&self) -> &ActionValue {
        &self.value
    }

    pub const fn sensitivity(&self) -> Sensitivity {
        self.sensitivity
    }
}

/// Data-only descriptor. It cannot contain a closure, executable code, grant,
/// token, or capability handle.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ActionDescriptor {
    pub(crate) id: ActionId,
    pub(crate) label: Option<LocalizedMessage>,
    pub(crate) parameters: Vec<ActionParameter>,
}

impl ActionDescriptor {
    pub fn new(
        id: ActionId,
        label: Option<LocalizedMessage>,
        parameters: Vec<ActionParameter>,
    ) -> Result<Self, ValidationError> {
        if parameters.len() > MAX_ACTION_PARAMETERS {
            return Err(ValidationError::TooManyActionParameters);
        }
        if label
            .as_ref()
            .is_some_and(|label| label.encoded_size() > MAX_CONTENT_BYTES)
        {
            return Err(ValidationError::ContentTooLarge);
        }
        let mut names = std::collections::BTreeSet::new();
        if parameters
            .iter()
            .any(|parameter| !names.insert(parameter.name.clone()))
        {
            return Err(ValidationError::DuplicateArgument);
        }
        if parameters
            .iter()
            .map(|parameter| parameter.name.len() + action_value_size(&parameter.value))
            .sum::<usize>()
            > MAX_CONTENT_BYTES
        {
            return Err(ValidationError::ContentTooLarge);
        }
        Ok(Self {
            id,
            label,
            parameters,
        })
    }

    pub fn id(&self) -> &ActionId {
        &self.id
    }

    pub fn label(&self) -> Option<&LocalizedMessage> {
        self.label.as_ref()
    }

    pub fn parameters(&self) -> &[ActionParameter] {
        &self.parameters
    }

    pub fn encoded_size(&self) -> usize {
        self.id.as_str().len()
            + self
                .label
                .as_ref()
                .map_or(0, LocalizedMessage::encoded_size)
            + self
                .parameters
                .iter()
                .map(|parameter| parameter.name.len() + action_value_size(&parameter.value))
                .sum::<usize>()
    }
}

