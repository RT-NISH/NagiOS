#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ValidationError {
    InvalidNotificationId,
    InvalidArgumentName,
    InvalidActionId,
    InvalidGroupingKey,
    InvalidSafeReference,
    EmptyContent,
    ContentTooLarge,
    TooManyArguments,
    TooManyActionParameters,
    DuplicateArgument,
    TooManyActions,
    InvalidExpiry,
    InvalidQueryLimit,
}

impl fmt::Display for ValidationError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::InvalidNotificationId => "notification id must be non-zero",
            Self::InvalidArgumentName => "invalid localized argument name",
            Self::InvalidActionId => "invalid action id",
            Self::InvalidGroupingKey => "invalid grouping key",
            Self::InvalidSafeReference => "invalid safe reference",
            Self::EmptyContent => "notification content is empty",
            Self::ContentTooLarge => "notification content exceeds its byte limit",
            Self::TooManyArguments => "too many localized arguments",
            Self::TooManyActionParameters => "too many action parameters",
            Self::DuplicateArgument => "duplicate argument name",
            Self::TooManyActions => "too many action descriptors",
            Self::InvalidExpiry => "expiry must be later than creation time",
            Self::InvalidQueryLimit => "query limit is outside the configured bound",
        })
    }
}

impl std::error::Error for ValidationError {}

fn valid_argument_name(value: &str) -> bool {
    !value.is_empty()
        && value.as_bytes()[0].is_ascii_alphabetic()
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
}

fn valid_action_id(value: &str) -> bool {
    if value.is_empty() || value.len() > 128 || value.starts_with('.') || value.ends_with('.') {
        return false;
    }
    let mut segments = value.split('.');
    let mut count = 0;
    for segment in &mut segments {
        count += 1;
        if segment.is_empty()
            || !segment.bytes().all(|byte| {
                byte.is_ascii_lowercase() || byte.is_ascii_digit() || matches!(byte, b'-' | b'_')
            })
        {
            return false;
        }
    }
    count >= 2
}

fn value_size(value: &ArgumentValue) -> usize {
    match value {
        ArgumentValue::Text(text) => text.len(),
        ArgumentValue::Signed(_) | ArgumentValue::Unsigned(_) => 8,
        ArgumentValue::Boolean(_) => 1,
        ArgumentValue::Redacted => 0,
    }
}

fn action_value_size(value: &ActionValue) -> usize {
    match value {
        ActionValue::Text(text) => text.len(),
        ActionValue::Signed(_) | ActionValue::Unsigned(_) => 8,
        ActionValue::Boolean(_) => 1,
        ActionValue::Redacted => 0,
    }
}
